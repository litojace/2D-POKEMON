import type { CharacterId } from "@arena/shared";
export type FxPoint = readonly [number, number];
export interface FxGlyph {
  kind: "path" | "dot" | "ring";
  points: readonly FxPoint[];
  closed?: boolean;
  radius?: number;
}
const p = (points: readonly FxPoint[], closed = false): FxGlyph => ({
  kind: "path",
  points,
  closed,
});
const r = (x: number, y: number, radius: number): FxGlyph => ({
  kind: "ring",
  points: [[x, y]],
  radius,
});
const d = (x: number, y: number, radius = 1): FxGlyph => ({
  kind: "dot",
  points: [[x, y]],
  radius,
});
