// Measures, once and offline, where each of Inkpurr's atlas pieces has
// painted pixels, and writes the table to apps/client/src/boss-inkpurr-trims.ts.
// The game then paints each piece straight into its trimmed size and never
// reads a pixel back. Re-run after changing a painter or a piece's box:
//
//   PW_CHROMIUM=/path/to/chrome node scripts/inkpurr-trims.mjs
//
// It starts the visual harness's Vite server on TRIM_PORT (default 4185).
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { chromium } from "playwright";

const port = Number(process.env.TRIM_PORT ?? 4185);
const root = process.cwd();
const server = spawn(
  "npx",
  [
    "vite",
    "--config",
    "tests/visual/vite.config.ts",
    "--port",
    String(port),
    "--strictPort",
  ],
  { stdio: "ignore" },
);
try {
  for (let i = 0; ; i++) {
    try {
      if ((await fetch(`http://localhost:${port}/`)).ok) break;
    } catch {
      /* not up yet */
    }
    if (i > 120) throw new Error("the Vite server did not start");
    await new Promise((r) => setTimeout(r, 500));
  }
  const browser = await chromium.launch({
    executablePath: process.env.PW_CHROMIUM || undefined,
  });
  const page = await browser.newPage();
  await page.route("**/trim-page", (r) =>
    r.fulfill({ contentType: "text/html", body: "<body></body>" }),
  );
  await page.goto(`http://localhost:${port}/trim-page`);
  const table = await page.evaluate(async (root) => {
    const paint = await import(
      `/@fs${root}/apps/client/src/boss-inkpurr-paint.ts`
    );
    const out = {};
    for (const p of paint.inkPieceSpecs()) {
      const c = paint.paintPieceCanvas(p.name, p.box, p.q, p.draw, p.opt);
      const { w, h } = c;
      const data = c.src.getContext("2d").getImageData(0, 0, w, h).data;
      let x0 = w,
        y0 = h,
        x1 = -1,
        y1 = -1;
      for (let y = 0; y < h; y++)
        for (let x = 0; x < w; x++)
          if (data[(y * w + x) * 4 + 3] > 3) {
            if (x < x0) x0 = x;
            if (x > x1) x1 = x;
            if (y < y0) y0 = y;
            if (y > y1) y1 = y;
          }
      // nothing painted (say, no drips seen from behind): a one-pixel cell
      if (x1 < 0) {
        out[p.name] = [0, 0, 1, 1];
        continue;
      }
      // two spare pixels each side: other browsers blur a hair differently
      x0 = Math.max(0, x0 - 2);
      y0 = Math.max(0, y0 - 2);
      x1 = Math.min(w - 1, x1 + 2);
      y1 = Math.min(h - 1, y1 + 2);
      out[p.name] = [x0, y0, x1 - x0 + 1, y1 - y0 + 1];
    }
    return out;
  }, root);
  await browser.close();
  const rows = Object.entries(table)
    .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(", ")}],`)
    .join("\n");
  writeFileSync(
    "apps/client/src/boss-inkpurr-trims.ts",
    `// Generated by scripts/inkpurr-trims.mjs: do not edit by hand.\n// Each Inkpurr atlas piece's painted pixels inside its full canvas: [x, y, w, h].\nexport const INK_TRIMS: Record<string, [number, number, number, number]> = {\n${rows}\n};\n`,
  );
  console.log(`${Object.keys(table).length} pieces measured`);
} finally {
  server.kill();
}
