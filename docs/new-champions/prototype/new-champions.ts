/**
 * Eight proposed champions, written in the same shape as CHARACTERS / COMBOS /
 * RITES in packages/shared/src/index.ts so they can be ported directly.
 *
 * New ability kinds used (each needs a small server change, see engine-patch.ts):
 *   "rush"  dash toward the aim for `range` px at `speed`; the first enemy touched
 *           takes the hit (+ `explosion` area if set) and the dash stops.
 *   "blink" teleport toward the aim, up to `range` px, stopping before walls; if
 *           `damage` > 0, a burst of `radius` hits enemies where you land.
 *   "veil"  self: stealth for `duration` (breaks on casting or taking damage, as the
 *           existing stealth status already does) plus haste for `statusDuration`.
 * New fields on existing kinds:
 *   knockback < 0  pulls the target toward the caster (clamped so it stops in front).
 *   zone + heal    each tick restores `heal` HP to teammates inside, and `selfHeal` x that to the caster.
 *   farBonus       up to this much extra damage at full range (Piper, Brawl Stars).
 *   wallSlam       rush: if the knockback would drive the target into a wall, x damage and a longer stun (Reinhardt).
 *   ambush         veil: the first hit dealt out of stealth is multiplied by this (Riki, Dota 2).
 */
