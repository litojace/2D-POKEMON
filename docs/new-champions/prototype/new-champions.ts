// Same defaults as the private helpers in packages/shared/src/index.ts.
const ability = (
  id: string,
  name: string,
  kind: NewKind,
  damage: number,
  cooldown: number,
  description: string,
  extra: Partial<Ability> = {},
): Ability =>
  ({
    id,
    name,
    kind,
    damage,
    cooldown,
    description,
    element: "",
    range: 700,
    cast: 0,
    recovery: 0.12,
    speed: 680,
    radius: 13,
    duration: 1,
    ground: false,
    knockback: 65,
    visual: kind,
    sound: kind,
    energyCost: 0,
    ...extra,
  }) as Ability;
const basic = (
  id: string,
  name: string,
  kind: NewKind,
  damage: number,
  intervalMs: number,
  description: string,
  extra: Partial<Ability> = {},
): Ability =>
  ability(id, name, kind, damage, 0, description, {
    interval: intervalMs / 1000,
    recovery: Math.min(0.12, intervalMs / 1000 / 2),
    knockback: 20,
    ...extra,
  });

